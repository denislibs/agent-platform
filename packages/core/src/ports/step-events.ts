/**
 * Уведомления «у задачи появились шаги» (спецификация 10). Подписчик (SSE) сам перечитывает шаги из хранилища:
 * сообщение несёт только последний seq. Доставка не гарантирована (pub/sub без хранения), поэтому подписчик
 * дополнительно перечитывает ленту по таймеру.
 */
export interface StepEvents {
  /** Шаги задачи записаны до lastSeq включительно. Вызывать только после коммита. */
  publish(taskId: string, lastSeq: number): Promise<void>;
  /** Промис резолвится, когда подписка уже действует. Результат — отписка; повторный вызов безопасен. */
  subscribe(taskId: string, onNotify: (lastSeq: number) => void): Promise<() => Promise<void>>;
}
