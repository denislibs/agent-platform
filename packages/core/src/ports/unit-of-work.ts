import type { CreditLedger, FileRepository, StepLog, SubtaskRepository, TaskRepository } from './repositories';

/** Репозитории, привязанные к одной транзакции. */
export interface TxRepositories {
  tasks: TaskRepository;
  steps: StepLog;
  subtasks: SubtaskRepository;
  ledger: CreditLedger;
  files: FileRepository;
  /**
   * Блокирует пользователя до конца транзакции: другие транзакции, вызвавшие lockUser для него же, ждут.
   * Так проверки «активных задач не больше лимита» и «баланс > 0» не гоняются с созданием задачи.
   * Неизвестный пользователь — NotFoundError('user').
   */
  lockUser(userId: string): Promise<void>;
}

/**
 * Несколько операций с репозиториями как одна транзакция (спецификация 4.1).
 * fn завершилась — всё записано; бросила — не записано ничего, а наружу уходит та же ошибка.
 *
 * Правила использования:
 * - Внутри fn — только tx. Репозитории из контейнера и вложенный run — ошибка использования.
 *   Вложенный run in-memory бросает сразу. В Postgres и вложенный run, и репозиторий из контейнера, упёршиеся
 *   в блокировку этой транзакции, падают по lock_timeout (ошибка 55P03, в доменную не переводится).
 *   Не упёрлись — запишутся мимо транзакции и не откатятся; in-memory репозиторий из контейнера не ловит.
 * - Вызовы на tx выполняются по одному: параллельные встают в очередь. Promise.all безопасен, но не ускоряет.
 * - Изоляция в Postgres — READ COMMITTED: с другими транзакциями сериализует только lockUser.
 *   Для «проверить, потом действовать» сначала lockUser, а смену статуса защищайте через expectedFrom.
 * - Порядок блокировок: сначала пользователь, потом задача. В одном run расход (ledger.record)
 *   записывайте раньше шагов (steps.append) той же задачи — иначе возможна взаимная блокировка (40P01).
 * - Не держите run открытым на время вызова LLM или песочницы: now() в Postgres — время начала транзакции,
 *   так что updated_at устареет, а блокировки будут висеть минутами.
 */
export interface UnitOfWork {
  run<T>(fn: (tx: TxRepositories) => Promise<T>): Promise<T>;
}
